/**
 * Currency configuration with symbols and formatting
 */
export interface CurrencyConfig {
  code: string;
  symbol: string;
  decimals: number;
  symbolPosition: 'prefix' | 'suffix';
}

export const CURRENCIES: Record<string, CurrencyConfig> = {
  PEN: { code: 'PEN', symbol: 'S/', decimals: 2, symbolPosition: 'prefix' },
  USD: { code: 'USD', symbol: '$', decimals: 2, symbolPosition: 'prefix' },
  EUR: { code: 'EUR', symbol: '€', decimals: 2, symbolPosition: 'prefix' },
  ILS: { code: 'ILS', symbol: '₪', decimals: 2, symbolPosition: 'prefix' },
  GBP: { code: 'GBP', symbol: '£', decimals: 2, symbolPosition: 'prefix' },
  BRL: { code: 'BRL', symbol: 'R$', decimals: 2, symbolPosition: 'prefix' },
  SAR: { code: 'SAR', symbol: 'ر.س', decimals: 2, symbolPosition: 'suffix' },
  CNY: { code: 'CNY', symbol: '¥', decimals: 2, symbolPosition: 'prefix' },
  JPY: { code: 'JPY', symbol: '¥', decimals: 0, symbolPosition: 'prefix' },
};

export function formatCurrency(amountCents: number, currencyCode = 'PEN'): string {
  const cfg = CURRENCIES[currencyCode] || CURRENCIES.PEN;
  const value = (amountCents / 100).toFixed(cfg.decimals);
  return cfg.symbolPosition === 'prefix' ? `${cfg.symbol} ${value}` : `${value} ${cfg.symbol}`;
}
